// 采样率(sample_rate)是"三重交替合成后"的真实采样率 = 4 × 144MHz / ((psc+1)×(arr+1))
//   · 实测：每来一次 TIM8 触发，DMA 从 CDR 搬回 4 个样本（用 1kHz 正弦反推，
//     一个周期正好 320 个样本 → 合成 320kSa/s，与"80kHz 触发 × 4"完全吻合）；
//   · 显示窗口固定为 24 × TimeBase，需要 2881 个样本，所以
//     慢档（≥20us）直接令 rate = 2881/(24×TimeBase) 并让 stretch 保持 1；
//     快档要保证"每个样本占满 24×TimeBase/2881 秒"，但触发率有硬件上限，
//     所以 rate 固定在 3.6MSa/s（触发 900kHz），靠 stretch 拉伸把窗口撑开。
//   · 触发率与溢出（OVR）：三重交替下一次触发要搬回 4 个样本，单个 ADC
//     一次转换 15 ADCCLK≈417ns，加上 2×DELAY(5 ADCCLK)≈278ns，一轮下来
//     约 1.1us。触发周期必须大于它，否则 ADC 溢出（OVR）：HAL 进错误态后
//     采集再也起不来，而软件触发还在跑，于是屏幕上只剩一条直线。
//     实测结论：800kHz（1250ns）稳定；1MHz（1000ns）会出问题；
//     这里取中间值 900kHz（1111ns），对应合成采样率 3.6MSa/s。
